// Regenerate after editing public HTML. --check rejects stale committed data.
import fs from 'node:fs';
import path from 'node:path';

const decode = text => text.replace(/&(?:amp|quot|apos|lt|gt|nbsp);|&#(?:x[0-9a-f]+|\d+);/gi, entity => {
  const named = { '&amp;': '&', '&quot;': '"', '&apos;': "'", '&lt;': '<', '&gt;': '>', '&nbsp;': ' ' };
  if (entity.startsWith('&#')) {
    const code = entity[2].toLowerCase() === 'x' ? parseInt(entity.slice(3), 16) : parseInt(entity.slice(2), 10);
    return code <= 0x10ffff ? String.fromCodePoint(code) : '';
  }
  return named[entity.toLowerCase()];
});
const plain = html => decode(html.replace(/<(script|style|nav|aside)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ')
  .replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
const files = [];
function visit(dir = '.') {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const file = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) visit(file);
    else if (file.endsWith('.html') && !['404.html', '_article-template.html'].includes(file)) files.push(file);
  }
}
visit();
const registry = [...fs.readFileSync('js/main.js', 'utf8').matchAll(/\{ title: '([^']*)', type: '([^']*)', url: '([^']*)' \}/g)]
  .map(([, title, type, url]) => ({ title, type, url }));
const aliases = {
  'characters/sarah-pu51fly.html': ['Sarah Wadmore', 'PFLY', 'P-fly', 'PU51FLY', 'P2FLY'],
  'characters/queen-sarah-pfly.html': ['Queen PFLY', 'Queen P-fly'],
  'characters/darren-cullen.html': ['SER', 'Darren Cullen'],
  'characters/charlie-buster.html': ['Charlie Buster', 'NFTBUSTER', 'Grime Art'],
  'factions/nomad-bears.html': ['Nomad Bares'],
  'factions/hodlwarriors.html': ['HODL Warriors'],
  'pages/waxp.html': ['WAX', 'WAXP', 'wallet', 'blockchain']
};
const index = files.sort().map(url => {
  const html = fs.readFileSync(url, 'utf8');
  const old = registry.find(entry => entry.url === url);
  const title = plain(html.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || html.match(/<title>(.*?)<\/title>/i)?.[1] || url);
  const summary = decode(html.match(/<meta\b[^>]*name="description"[^>]*content="([^"]*)"/i)?.[1] || '');
  const text = plain(html.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i)?.[1] || '');
  return { title, type: old?.type || 'Page', url, summary, aliases: [old?.title || title, url.replace(/[/.\-]/g, ' '), ...(aliases[url] || [])], text };
});
const result = '// Generated by scripts/build-search-index.mjs; do not edit.\nwindow.GK_SEARCH_INDEX = ' + JSON.stringify(index) + ';\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync('js/search-index.js') || fs.readFileSync('js/search-index.js', 'utf8') !== result) {
    console.error('Search index is stale. Run node scripts/build-search-index.mjs');
    process.exitCode = 1;
  } else console.log('Search index is current: ' + index.length + ' pages.');
} else {
  fs.writeFileSync('js/search-index.js', result);
  console.log('Built full-text search index: ' + index.length + ' pages, ' + Math.round(Buffer.byteLength(result) / 1024) + ' KiB (loaded on demand).');
}
